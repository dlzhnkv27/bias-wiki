"""Build Russian assets: SVG map and bias descriptions."""
import glob, html, json, re, urllib.parse

ROOT = '.'
labels_ru = json.load(open('i18n/labels_ru.json'))
biases = json.load(open('i18n/biases_en.json'))
ru_wiki = {b['name']: b['ru_wiki'] for b in biases if 'ru_wiki' in b}


def norm(name):
    return name.lower().replace('–', '-').strip()


ru_wiki_by_norm = {norm(k): v for k, v in ru_wiki.items()}

# --- SVG ---
svg = open('assets/images/cognitive_bias_codex_en.svg', encoding='utf-8').read()
svg = re.sub(r'<text[^>]*systemLanguage="[^"]*"[^>]*>.*?</text>', '', svg, flags=re.S)
svg = re.sub(r'<switch[^>]*>|</switch>', '', svg)
svg = svg.replace('xml:lang="en-us"', 'xml:lang="ru"').replace(
    '<title>The Cognitive Bias Codex</title>', '<title>Кодекс когнитивных искажений</title>')

counter = iter(range(len(labels_ru)))


def repl_text(m):
    ru = labels_ru[next(counter)]
    spans = iter(ru)
    body = re.sub(r'(<tspan[^>]*>).*?(</tspan>)', lambda t: t.group(1) + html.escape(next(spans), quote=False) + t.group(2), m.group(2), flags=re.S)
    return m.group(1) + body + m.group(3)


# remember English names for links before replacing text
def repl_a(m):
    en = re.sub(r'<[^>]+>', '', re.search(r'<text[^>]*>(.*?)</text>', m.group(0), re.S).group(1)).strip()
    href = m.group(2)
    if norm(en) in ru_wiki_by_norm and '#' not in href:
        href = 'https://ru.wikipedia.org/wiki/' + ru_wiki_by_norm[norm(en)].replace(' ', '_')
    return f'<a data-bias="{html.escape(en)}" xlink:href="{html.escape(href)}"{m.group(3)}'


svg = re.sub(r'<a( )xlink:href="([^"]*)"(>.*?</a>)', repl_a, svg, flags=re.S)
svg = re.sub(r'(<text[^>]*>)(.*?)(</text>)', repl_text, svg, flags=re.S)
assert next(counter, None) is None, 'label count mismatch'
open('assets/images/cognitive_bias_codex_ru.svg', 'w', encoding='utf-8').write(svg)

# --- descriptions ---
def clean(h):
    """Drop Wikipedia scraping residue: empty paragraphs and pronunciation parentheticals."""
    h = re.sub(r'<p class="mw-empty-elt">\s*</p>', '', h)
    h = re.sub(r'\s*\((?:\s|;|<span></span>|<span><span>[^<]*</span></span>'
               r'|<i title="English pronunciation respelling">.*?</i>)+\)', '', h)
    return h.strip()


tr = {}
for f in sorted(glob.glob('i18n/chunks/ru_*.json')):
    tr.update({k: clean(v) for k, v in json.load(open(f)).items()})
out = ['<html><body>']
missing = []
for b in biases:
    src = b.get('same_as', b['name'])
    if src not in tr:
        missing.append(b['name'])
        continue
    url = b['url']
    if b['name'] in ru_wiki and '#' not in url:
        url = 'https://ru.wikipedia.org/wiki/' + urllib.parse.quote(ru_wiki[b['name']].replace(' ', '_'))
    out.append(f"<div class='bias'>\n<h2>{b['name']}</h2>\n<a href='{url}' target='_blank'>Википедия</a>\n"
               f"<div class='content'>{tr[src]}</div>\n"
               f"<div class='attribution'>Перевод материалов <a href='{b['url']}'>Википедии</a>, лицензия "
               f"<a href='https://creativecommons.org/licenses/by-sa/3.0/'>CC BY-SA 3.0</a></div>\n</div>")
out.append('</body></html>')
open('biases_wikipedia_ru.html', 'w', encoding='utf-8').write('\n'.join(out))
print('svg ok; descriptions:', len(biases) - len(missing), 'missing:', len(missing))

# --- inline bundle so index.html works when opened from disk ---
files = sorted(glob.glob('assets/images/cognitive_bias_codex_*.svg')) + ['biases_wikipedia.html', 'biases_wikipedia_ru.html']
data = {f: open(f, encoding='utf-8').read() for f in files}
with open('assets/js/inline_data.js', 'w', encoding='utf-8') as f:
    f.write('// Generated by i18n/build_ru.py\nwindow.INLINE_DATA = ' + json.dumps(data, ensure_ascii=False) + ';\n')
print('inline bundle:', len(files), 'files')
